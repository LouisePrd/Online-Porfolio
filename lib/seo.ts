import type { Metadata } from "next";
import type { Lang } from "@/content/site";

/**
 * Public URL of the site. Netlify sets `URL` at build time (primary domain);
 * SITE_URL can override it. Used to build absolute links for sharing previews.
 */
export const SITE_URL = (process.env.SITE_URL ?? process.env.URL ?? "http://localhost:3000").replace(/\/$/, "");

export const SITE_NAME = "Louise Peridy";

/** Path of a page in the other language: "/projects" <-> "/en/projects". */
export const enPath = (frPath: string) => (frPath === "/" ? "/en" : `/en${frPath}`);

/**
 * Title, description, canonical, hreflang, Open Graph and Twitter tags for one page.
 * `frPath` is the French path; the English one is derived from it.
 */
export function pageMeta(lang: Lang, frPath: string, title: string, description: string): Metadata {
  const url = lang === "fr" ? frPath : enPath(frPath);
  // Generated by app/og/[lang]/route.tsx.
  const image = {
    url: `/og/${lang}`,
    width: 1200,
    height: 630,
    alt: lang === "fr" ? "Louise Peridy, développeuse créative" : "Louise Peridy, creative developer",
  };
  return {
    title,
    description,
    alternates: {
      canonical: url,
      languages: { fr: frPath, en: enPath(frPath), "x-default": frPath },
    },
    openGraph: {
      type: "website",
      siteName: SITE_NAME,
      locale: lang === "fr" ? "fr_FR" : "en_US",
      alternateLocale: lang === "fr" ? "en_US" : "fr_FR",
      url,
      title,
      description,
      images: [image],
    },
    twitter: { card: "summary_large_image", title, description, images: [image] },
  };
}
